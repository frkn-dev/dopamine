    QJsonArray subnetsJson(const char *const *subnets, size_t count)
    {
        QJsonArray domains;
        for (size_t i = 0; i < count; ++i) {
            domains.append(QString::fromLatin1(subnets[i]));
        }
        return domains;
    }
